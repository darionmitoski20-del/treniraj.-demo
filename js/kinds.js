// Типови на тренер: изберени од тренерот, а ако нема избор се погодуваат од спортовите.
export function kindsOf(t) {
  if (t && t.kinds && t.kinds.length) return t.kinds;
  const sp = (t && t.sports) || [];
  const found = KIND_IDS.filter((k) => KINDS[k].sports.some((x) => sp.includes(x)));
  return found.length ? found : ['gym'];
}

export function features(t) {
  const kinds = kindsOf(t);
  const planKinds = [...new Set(kinds.map((k) => KINDS[k].plan))];
  const recipes = kinds.some((k) => KINDS[k].recipes);
  const plansLabel = kinds.length === 1 ? KINDS[kinds[0]].plansLabel : planKinds.length === 1 ? 'Планови' : 'Планови';
  return { kinds, planKinds, recipes, plansLabel, recipesFirst: kinds.length === 1 && kinds[0] === 'nutri' };
}

export function kindLabels(t) { return kindsOf(t).map((k) => KINDS[k].label); }

